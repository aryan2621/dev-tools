use rquickjs::{Context, Ctx, Runtime};
use serde_json::Value;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

const MAX_SANDBOX_JSON_BYTES: usize = 256 * 1024;
const MAX_SANDBOX_MEMORY: usize = 64 * 1024 * 1024;
const MAX_SANDBOX_STACK: usize = 1024 * 1024;
/// Hard wall-clock cap, including time spent waiting on host `callTool` calls.
const MAX_SANDBOX_WALL: Duration = Duration::from_secs(15 * 60);
/// `callTool(name, args)` returns what the tool produced, not the MCP envelope: `structuredContent`
/// when present, else the text content (parsed as JSON when it is JSON). Failures and `isError` throw.
const CALL_TOOL_PRELUDE: &str = r#"globalThis.callTool = function (name, args) {
  const r = JSON.parse(__callTool(String(name), JSON.stringify(args === undefined ? {} : args)));
  if (r && typeof r.error === "string" && Object.keys(r).length === 1) throw new Error(r.error);
  const text = Array.isArray(r && r.content)
    ? r.content.filter((c) => c && c.type === "text").map((c) => c.text).join("\n")
    : "";
  if (r && r.isError) throw new Error(text || "The tool returned an error.");
  if (r && r.structuredContent !== undefined) return r.structuredContent;
  if (!text) return r;
  try { return JSON.parse(text); } catch (_) { return text; }
};"#;
/// QuickJS has no console. Capture output so scripts that print instead of `return` still show something.
const CONSOLE_PRELUDE: &str = r#"globalThis.global = globalThis; // Node habit: `global.callTool`
globalThis.__logs = [];
(function () {
  const fmt = (v) => {
    if (typeof v === "string") return v;
    if (v instanceof Error) return v.name + ": " + v.message;
    try { const s = JSON.stringify(v); return s === undefined ? String(v) : s; } catch (_) { return String(v); }
  };
  const log = (level) => (...a) => {
    if (__logs.length < 200) __logs.push(level + a.map(fmt).join(" "));
  };
  globalThis.console = { log: log(""), info: log(""), debug: log(""), warn: log("warn: "), error: log("error: ") };
})();"#;
const FINALIZE: &str = r#"(function () {
  const logs = __logs.length ? "\n\nConsole output:\n" + __logs.join("\n") : "";
  if (__err !== undefined) { __err += logs; return; }
  if (!__done) return;
  try {
    const v = __value === undefined ? null : __value;
    const s = JSON.stringify(__logs.length ? { result: v, logs: __logs } : v);
    __out = s === undefined ? "null" : s;
  } catch (e) {
    __err = "The return value is not JSON-serializable: " + (e && e.message ? e.message : String(e));
  }
})();"#;
const TIMED_OUT: &str = "Code execution timed out.";

/// Models write module-style `import { callTool } from "..."`; there are no modules and
/// `callTool` is already global, so drop those lines instead of failing with a SyntaxError.
// shortcut: line-based, so an import split over several lines still fails; parse if models do that.
fn strip_imports(code: &str) -> String {
    code.lines()
        .filter(|line| {
            !line
                .trim_start()
                .strip_prefix("import")
                .is_some_and(|rest| rest.starts_with([' ', '{', '*', '"', '\'']))
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// JS time budget. Time spent inside host `callTool` (user approval, the tool call)
/// does not count against it; `cancelled` stops the script at the next interrupt check.
struct Budget {
    deadline: Mutex<Instant>,
    cancelled: AtomicBool,
}

impl Budget {
    fn exhausted(&self) -> bool {
        self.cancelled.load(Ordering::Relaxed) || Instant::now() >= *self.deadline.lock().unwrap()
    }
}

/// `Error::Exception` only says "Exception generated by QuickJS"; the real message is on the context.
fn js_error(ctx: &Ctx<'_>, e: rquickjs::Error) -> String {
    if !matches!(e, rquickjs::Error::Exception) {
        return e.to_string();
    }
    describe(&ctx.catch())
}

fn describe(thrown: &rquickjs::Value<'_>) -> String {
    if let Some(ex) = thrown.as_exception() {
        let name: String = ex.get("name").unwrap_or_else(|_| "Error".into());
        return format!("{name}: {}", ex.message().unwrap_or_default());
    }
    match thrown.as_string().and_then(|s| s.to_string().ok()) {
        Some(s) => s,
        None => format!("Script threw: {thrown:?}"),
    }
}

/// Evaluate JavaScript and return JSON. Host `callTool` is injected when a hook is provided.
fn run_javascript(
    code: String,
    budget: Arc<Budget>,
    call_tool: Option<impl Fn(String, Value) -> Result<Value, String> + Send + Sync + 'static>,
) -> Result<Value, String> {
    let runtime = Runtime::new().map_err(|e| e.to_string())?;
    runtime.set_memory_limit(MAX_SANDBOX_MEMORY);
    runtime.set_max_stack_size(MAX_SANDBOX_STACK);
    let interrupt_budget = budget.clone();
    runtime.set_interrupt_handler(Some(Box::new(move || interrupt_budget.exhausted())));
    let unhandled: Arc<Mutex<Option<String>>> = Arc::default();
    let tracker_slot = unhandled.clone();
    runtime.set_host_promise_rejection_tracker(Some(Box::new(
        move |_ctx, _promise, reason, is_handled| {
            let mut slot = tracker_slot.lock().unwrap();
            if is_handled {
                *slot = None;
            } else if slot.is_none() {
                *slot = Some(describe(&reason));
            }
        },
    )));
    let context = Context::full(&runtime).map_err(|e| e.to_string())?;
    let result = context.with(|ctx| {
        if let Some(call_tool) = call_tool {
            let hook_budget = budget.clone();
            let callback = rquickjs::function::MutFn::new(
                move |name: String, args_json: String| -> String {
                    if hook_budget.cancelled.load(Ordering::Relaxed) {
                        return serde_json::json!({ "error": TIMED_OUT }).to_string();
                    }
                    let args: Value = serde_json::from_str(&args_json)
                        .unwrap_or(Value::Object(Default::default()));
                    let started = Instant::now();
                    let out = call_tool(name, args);
                    *hook_budget.deadline.lock().unwrap() += started.elapsed();
                    match out {
                        Ok(v) => serde_json::to_string(&v).unwrap_or_else(|_| "{}".into()),
                        Err(e) => serde_json::json!({ "error": e }).to_string(),
                    }
                },
            );
            let call = rquickjs::Function::new(ctx.clone(), callback).map_err(|e| e.to_string())?;
            ctx.globals()
                .set("__callTool", call)
                .map_err(|e| e.to_string())?;
            // Scripts pass an object and get the parsed result back; a failed call throws.
            ctx.eval::<(), _>(CALL_TOOL_PRELUDE)
                .map_err(|e| js_error(&ctx, e))?;
        }
        ctx.eval::<(), _>(CONSOLE_PRELUDE)
            .map_err(|e| js_error(&ctx, e))?;
        // The body runs in an async function so scripts may `await` and must `return` their value.
        let code = strip_imports(&code);
        let wrapped = format!(
            r#"globalThis.__done = false; globalThis.__value = undefined; globalThis.__out = undefined; globalThis.__err = undefined;
(async function () {{
{code}
}})().then(
  (v) => {{ __value = v; __done = true; }},
  (e) => {{ __err = e instanceof Error ? e.name + ": " + e.message : String(e); }},
);"#
        );
        ctx.eval::<(), _>(wrapped).map_err(|e| js_error(&ctx, e))?;
        // Ctx::execute_pending_job, not Runtime's: the runtime is already borrowed inside `with`.
        while ctx.execute_pending_job() {}
        // Serialize only after every job ran, so un-awaited `main().then(console.log)` output is kept.
        // Console output rides along: `{ result, logs }` on success, appended to the message on failure.
        ctx.eval::<(), _>(FINALIZE).map_err(|e| js_error(&ctx, e))?;
        if let Some(reason) = unhandled.lock().unwrap().take() {
            let logs: String = ctx.eval("__logs.join('\\n')").unwrap_or_default();
            let logs = if logs.is_empty() { logs } else { format!("\n\nConsole output:\n{logs}") };
            return Err(format!(
                "Unhandled promise rejection: {reason}. An async call was not awaited; `return await` it.{logs}"
            ));
        }
        let globals = ctx.globals();
        if let Some(err) = globals.get::<_, Option<String>>("__err").map_err(|e| js_error(&ctx, e))? {
            return Err(err);
        }
        let out: String = globals
            .get::<_, Option<String>>("__out")
            .map_err(|e| js_error(&ctx, e))?
            .ok_or("Script did not finish (a promise never resolved).")?;
        if out.len() > MAX_SANDBOX_JSON_BYTES {
            return Err("Sandbox output exceeded 256 KB.".into());
        }
        serde_json::from_str(&out).map_err(|e| format!("Sandbox returned invalid JSON: {e}"))
    });
    if result.is_err() && budget.exhausted() {
        return Err(TIMED_OUT.into());
    }
    result
}

/// Run with `timeout` of JavaScript time. The engine is interrupted when the budget runs
/// out, so the worker thread always exits instead of spinning in the background.
pub fn run_javascript_with_timeout(
    code: String,
    timeout: Duration,
    call_tool: Option<impl Fn(String, Value) -> Result<Value, String> + Send + Sync + 'static>,
) -> Result<Value, String> {
    let budget = Arc::new(Budget {
        deadline: Mutex::new(Instant::now() + timeout),
        cancelled: AtomicBool::new(false),
    });
    let (tx, rx) = std::sync::mpsc::sync_channel(1);
    let worker_budget = budget.clone();
    std::thread::spawn(move || {
        let _ = tx.send(run_javascript(code, worker_budget, call_tool));
    });
    match rx.recv_timeout(MAX_SANDBOX_WALL) {
        Ok(result) => result,
        Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => {
            Err("The sandbox crashed while running the script.".into())
        }
        Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
            budget.cancelled.store(true, Ordering::Relaxed);
            Err(TIMED_OUT.into())
        }
    }
}
